/**
 * Deciding where an imported PGP key belongs.
 *
 * A key file carries no notion of accounts. It carries user IDs, and a user ID carries an
 * address. Matching those addresses against the accounts set up here is the whole of the
 * mapping, and keeping it as a plain function means the awkward cases (one key for several
 * aliases, two keys claiming one account, a key that is already stored) can be shown to the
 * user instead of being resolved silently.
 */

export interface ScannedKey {
  fingerprint: string
  /** Full user IDs, for display. `Name <address>`. */
  userIds: string[]
  /** Just the addresses, lower-cased, which is what the mapping runs on. */
  addresses: string[]
  hasPrivate: boolean
  /** False when the private key material is still sealed behind a passphrase. */
  privateUnlocked: boolean
  createdAt: string
  /** Null when the key does not expire. */
  expiresAt: string | null
}

export interface AccountAddress {
  id: string
  emailAddress: string
}

export type KeyNote =
  /** Private material present but sealed. The passphrase decides whether this key is usable. */
  | 'locked'
  /**
   * Sealed with a passphrase nobody can supply.
   *
   * Thunderbird generates that passphrase itself and keeps it in its own password store, so
   * asking the user for it would be asking for something they have never seen. Distinct from
   * `locked`, where typing the passphrase is exactly what is called for.
   */
  | 'sealedExternally'
  /** Past its expiry date. Still worth importing: old mail stays encrypted to it. */
  | 'expired'
  /** A key with this fingerprint is already stored here. */
  | 'alreadyPresent'
  /** Matches an account, but brings no private half. That account could not decrypt with it. */
  | 'publicOnly'
  /**
   * Another key in the same file carries one of the same addresses.
   *
   * No longer a reason to refuse: an account holds a ring, so both can come in and the newest
   * becomes the one that signs. Still worth saying, because which one ends up active is a
   * decision being made on the user's behalf.
   */
  | 'severalForOneAccount'

export interface KeyAssignment {
  key: ScannedKey
  /** Accounts carrying one of this key's addresses; more than one when aliases share a key. */
  accountIds: string[]
  /** Set only when the key belongs to no account here. Then it is filed under this address. */
  contactAddress: string | null
  notes: KeyNote[]
}

/** The address a contact key is filed under: the first user ID is the primary one. */
function primaryAddress(key: ScannedKey): string | null {
  return key.addresses[0] ?? null
}

export interface AssignOptions {
  /** Fingerprints already stored here, so nothing is offered as new that is not. */
  knownFingerprints?: string[]
  /**
   * Whether the user can supply the passphrase for a sealed key.
   *
   * True for a file they exported themselves. False for Thunderbird's own rings, where the
   * passphrase was generated by Thunderbird. There, a sealed key can only be taken over as
   * its public half, which is no use to an account of one's own.
   */
  passphraseAvailable?: boolean
  now?: Date
}

export function assignKeys(
  keys: ScannedKey[],
  accounts: AccountAddress[],
  options: AssignOptions = {}
): KeyAssignment[] {
  const { knownFingerprints = [], passphraseAvailable = true, now = new Date() } = options
  const byAddress = new Map(accounts.map((a) => [a.emailAddress.toLowerCase(), a.id]))
  const known = new Set(knownFingerprints.map((f) => f.toLowerCase()))

  const assignments: KeyAssignment[] = keys.map((key) => {
    const accountIds = [...new Set(key.addresses.map((a) => byAddress.get(a)).filter(isString))]
    const notes: KeyNote[] = []

    // Only said where it changes anything. A contact key is the public half by definition, so
    // a sealed private half costs it nothing. And a warning on a row that imports fine
    // contradicts itself.
    if (accountIds.length > 0 && key.hasPrivate && !key.privateUnlocked) {
      notes.push(passphraseAvailable ? 'locked' : 'sealedExternally')
    }
    if (key.expiresAt && new Date(key.expiresAt) < now) notes.push('expired')
    if (known.has(key.fingerprint.toLowerCase())) notes.push('alreadyPresent')
    // Only worth saying where it costs something: a public-only key for a stranger is
    // exactly what one wants, while a public-only key for one's own account is a dead end.
    if (accountIds.length > 0 && !key.hasPrivate) notes.push('publicOnly')

    return {
      key,
      accountIds,
      contactAddress: accountIds.length === 0 ? primaryAddress(key) : null,
      notes
    }
  })

  markConflicts(assignments)
  return assignments
}

/**
 * Flags accounts that more than one key in this file belongs to.
 *
 * Both are kept, since an account holds a ring, but only one can be the key that signs, and
 * newest wins. Said out loud rather than decided silently: the file cannot know which key its
 * owner considers current, so the choice is at least visible.
 */
function markConflicts(assignments: KeyAssignment[]): void {
  const claims = new Map<string, KeyAssignment[]>()
  for (const assignment of assignments) {
    for (const accountId of assignment.accountIds) {
      const list = claims.get(accountId)
      if (list) list.push(assignment)
      else claims.set(accountId, [assignment])
    }
  }

  for (const contenders of claims.values()) {
    if (contenders.length < 2) continue
    for (const assignment of contenders) {
      if (!assignment.notes.includes('severalForOneAccount')) assignment.notes.push('severalForOneAccount')
    }
  }
}

function isString(value: string | null | undefined): value is string {
  return typeof value === 'string'
}

/**
 * Whether importing this key would actually achieve anything.
 *
 * Pre-selection follows this: offering a checkbox that cannot lead anywhere teaches the user
 * to tick boxes without reading them.
 */
export function isImportable(assignment: KeyAssignment): boolean {
  if (assignment.notes.includes('alreadyPresent')) return false

  if (assignment.accountIds.length > 0) {
    // An account key without usable private material cannot decrypt or sign, and a key sealed
    // by another program is exactly that: present, but permanently shut.
    if (assignment.notes.includes('sealedExternally')) return false
    return assignment.key.hasPrivate
  }
  // Contact keys are the public half by definition, so being sealed costs them nothing.
  return assignment.contactAddress !== null
}

/** Addresses in a user ID, as `Name <a@b>` or a bare address. */
export function addressesFromUserIds(userIds: string[]): string[] {
  const found = userIds
    .map((uid) => /<([^>]+)>/.exec(uid)?.[1] ?? (uid.includes('@') ? uid : null))
    .filter(isString)
    .map((a) => a.trim().toLowerCase())
  return [...new Set(found)]
}
